create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_set_updated_at on public.embalagens;
create trigger trg_set_updated_at
before update on public.embalagens
for each row
execute function public.set_updated_at();

create policy "Allow all reads and writes for anonymous"
on public.embalagens
for all
to anon
using (true)
with check (true);
